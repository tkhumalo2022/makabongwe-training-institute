-- Makabongwe Online Institute — Neon PostgreSQL starter schema
-- REVIEW ONLY. Do not execute against the current Supabase production database.
-- Student number is the canonical primary key; never use South African ID or passport number as primary key.
-- All tables are server-access only. No public data API or unauthorised browser SQL access.

begin;
create extension if not exists pgcrypto;

create sequence if not exists public.mti_student_number_sequence start with 1 increment by 1;
create or replace function public.mti_next_student_number() returns text
language sql volatile as $$
  select 'MTI-' || to_char(now() at time zone 'Africa/Johannesburg', 'YYYY') || '-' ||
         case when number_value < 1000000 then lpad(number_value::text, 6, '0')
              else number_value::text end
  from (select nextval('public.mti_student_number_sequence') as number_value) allocated;
$$;

create table if not exists public.mti_students (
  student_number text primary key default public.mti_next_student_number()
    check (student_number ~ '^MTI-[0-9]{4}-[0-9]{6,}$'),
  full_name text not null check (char_length(trim(full_name)) between 3 and 160),
  email text not null check (char_length(email) between 5 and 254),
  status text not null default 'active' check (status in ('active','suspended','alumni')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists mti_students_email_ci on public.mti_students(lower(email));

create table if not exists public.mti_courses (
  id bigint generated by default as identity primary key,
  source_programme_id bigint unique, -- optional link to migrated cms_programmes.id
  slug text not null unique check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  title text not null check (char_length(title) between 2 and 160),
  description text not null default '',
  status text not null default 'draft' check (status in ('draft','published','archived')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Editable programme metadata used by the administrative intranet.
-- Keep this additive for existing Neon preview branches and future migrations.
alter table public.mti_courses add column if not exists department text not null default 'Agricultural Training';
alter table public.mti_courses add column if not exists duration text not null default 'To be confirmed';
alter table public.mti_courses add column if not exists delivery_mode text not null default 'Contact learning';
alter table public.mti_courses add column if not exists location text not null default 'To be confirmed';
alter table public.mti_courses add column if not exists available_intake text;
alter table public.mti_courses add column if not exists image_url text;
alter table public.mti_courses add column if not exists price_cents integer not null default 0;
alter table public.mti_courses add column if not exists registration_fee_cents integer not null default 0;
alter table public.mti_courses add column if not exists sort_order integer not null default 0;
alter table public.mti_courses add column if not exists is_available boolean not null default false;
create table if not exists public.mti_course_enrolments (
  student_number text not null references public.mti_students(student_number) on update restrict on delete restrict,
  course_id bigint not null references public.mti_courses(id) on delete restrict,
  status text not null default 'enrolled' check (status in ('pending','enrolled','completed','withdrawn')),
  enrolled_at timestamptz not null default now(),
  primary key (student_number,course_id)
);
create index if not exists mti_course_enrolments_by_course on public.mti_course_enrolments(course_id,status);

create table if not exists public.mti_course_modules (
  id uuid primary key default gen_random_uuid(),
  course_id bigint not null references public.mti_courses(id) on delete cascade,
  title text not null check (char_length(title) between 2 and 160),
  summary text not null default '',
  content text not null default '',
  sort_order integer not null default 0 check(sort_order>=0),
  is_published boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists mti_modules_course_order on public.mti_course_modules(course_id,sort_order);

create table if not exists public.mti_course_announcements (
  id uuid primary key default gen_random_uuid(),
  course_id bigint not null references public.mti_courses(id) on delete cascade,
  title text not null check (char_length(title) between 2 and 160),
  body text not null check (char_length(body) between 2 and 4000),
  is_published boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists mti_announcements_by_course on public.mti_course_announcements(course_id,created_at desc);

create table if not exists public.mti_course_resources (
  id uuid primary key default gen_random_uuid(),
  course_id bigint not null references public.mti_courses(id) on delete cascade,
  module_id uuid references public.mti_course_modules(id) on delete set null,
  title text not null check(char_length(title) between 2 and 160),
  url text not null,
  is_published boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists mti_resources_by_course on public.mti_course_resources(course_id);

create table if not exists public.mti_course_progress (
  student_number text not null,
  course_id bigint not null,
  module_id uuid not null references public.mti_course_modules(id) on delete cascade,
  completed_at timestamptz not null default now(),
  primary key(student_number,course_id,module_id),
  foreign key(student_number,course_id)
    references public.mti_course_enrolments(student_number,course_id) on delete cascade
);

create table if not exists public.mti_student_login_codes (
  id uuid primary key default gen_random_uuid(),
  student_number text not null references public.mti_students(student_number) on delete cascade,
  code_hash text not null,
  attempts integer not null default 0,
  expires_at timestamptz not null,
  consumed_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists mti_login_active_by_student on public.mti_student_login_codes(student_number,created_at desc);

create table if not exists public.mti_email_outbox (
  id uuid primary key default gen_random_uuid(),
  student_number text not null references public.mti_students(student_number) on delete restrict,
  course_id bigint references public.mti_courses(id) on delete set null,
  recipient text not null,
  kind text not null check(kind in ('welcome','course-enrolment','announcement','login-code')),
  subject text not null,
  body text not null,
  state text not null default 'queued' check(state in ('queued','sent','failed')),
  provider_message_id text,
  error_summary text,
  created_at timestamptz not null default now(),
  sent_at timestamptz
);
create index if not exists mti_email_queue_state on public.mti_email_outbox(state,created_at);

-- Application checks verified student session + course enrolment before serving any
-- modules, announcements, resources or progress. Never expose the DB connection
